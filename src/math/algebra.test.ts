import { describe, expect, it } from 'vitest'
import {
  AlgError, AlgSpec, checkAlgebra, fmtPoly, parsePoly, parseRat, pDivide, pDivExact, pretty, prim, rationalRoots,
  solveEquation, fmtFrac, rEq,
} from './algebra'

const ex = (s: string) => fmtPoly(parsePoly(s), true)
const spec = (mode: AlgSpec['mode'], answer: string, source = answer, solveFor?: string): AlgSpec => ({ mode, source, answer, solveFor })
const ok = (s: AlgSpec, t: string) => checkAlgebra(s, t).ok

describe('polynomial engine', () => {
  it('expands and formats in standard form', () => {
    expect(ex('(x+2)(x-3)')).toBe('x^2 - x - 6')
    expect(ex('(x+y)^3')).toBe('x^3 + 3x^2y + 3xy^2 + y^3')
    expect(ex('(2x-y)(4x^2+2xy+y^2)')).toBe('8x^3 - y^3')
    expect(ex('(x + y - z)^2')).toBe('x^2 + 2xy - 2xz + y^2 - 2yz + z^2')
    expect(fmtPoly(parsePoly('x^3-2x'))).toBe('x³ − 2x')
    expect(pretty('x^2 - 3')).toBe('x² − 3')
  })
  it('reads many ways of typing the same thing', () => {
    for (const t of ['x²+2x+1', 'x^2+2*x+1', 'x^2 + 2x + 1', '(x+1)^2', '(x+1)(x+1)', '(x + 1)²', 'x*x + 2 x + 1', 'X^2+2X+1', '1+2x+x^2', 'x^(2)+2x+1'])
      expect(ex(t), t).toBe('x^2 + 2x + 1')
    expect(ex('2(x+3)')).toBe('2x + 6')
    expect(ex('-x^2')).toBe('-x^2')
    expect(ex('0.5x+1/2')).toBe('(1/2)x + 1/2')
  })
  it('rejects ambiguous or unreadable input with a message', () => {
    for (const t of ['x2', '1/2x', '(x+1', 'x^y', 'sqrt(4)', '3 4', 'x+', '', 'x=2']) expect(() => parseRat(t), t).toThrow(AlgError)
  })
  it('divides exactly and with remainder, in several variables', () => {
    const n = parsePoly('x^3 - y^3'), d = parsePoly('x - y')
    expect(fmtPoly(pDivExact(n, d)!, true)).toBe('x^2 + xy + y^2')
    const { q, r } = pDivide(parsePoly('x^3 + 2x^2 - 5x + 1'), parsePoly('x - 2'))
    expect(fmtPoly(q, true)).toBe('x^2 + 4x + 3')
    expect(fmtPoly(r, true)).toBe('7')
    expect(pDivExact(parsePoly('x^2+1'), parsePoly('x-1'))).toBeNull()
  })
  it('normalises to a primitive polynomial', () => {
    const { p, c } = prim(parsePoly('-6x^2 + 9x'))
    expect(fmtPoly(p, true)).toBe('2x^2 - 3x')
    expect(fmtFrac(c)).toBe('−3')
  })
  it('finds rational roots', () => {
    const r = rationalRoots(parsePoly('x^3 - 2x^2 - 5x + 6'))
    expect(r.roots.map(fmtFrac)).toEqual(['−2', '1', '3'])
    expect(r.complete).toBe(true)
    expect(rationalRoots(parsePoly('2x^2 - 3x - 2')).roots.map(fmtFrac)).toEqual(['−1/2', '2'])
    expect(rationalRoots(parsePoly('x^3 - 8')).complete).toBe(false)
    expect(rationalRoots(parsePoly('x^3 - 8')).roots.map(fmtFrac)).toEqual(['2'])
    expect(rationalRoots(parsePoly('x^3 - 4x')).roots.map(fmtFrac)).toEqual(['−2', '0', '2'])
  })
  it('solves rational equations and drops extraneous roots', () => {
    const s = solveEquation(parseRat('x/(x-3)'), parseRat('3/(x-3) + 1'))
    expect(s.roots).toEqual([]) // x - 3 cancels to 1 = 1 ... identity? no: x = 3 + x - 3
    const t = solveEquation(parseRat('x/(x-2)'), parseRat('2/(x-2)'))
    expect(t.roots).toEqual([])
    expect(t.extraneous.map(fmtFrac)).toEqual(['2'])
    const u = solveEquation(parseRat('1/x + 1/(x-1)'), parseRat('1'))
    expect(u.complete).toBe(false)
    const w = solveEquation(parseRat('1/x + 1/(x-1)'), parseRat('3/2'))
    expect(w.roots.map(fmtFrac)).toEqual(['1/3', '2'])
  })
})

describe('checking answers', () => {
  it('expanded form: value and shape', () => {
    const s = spec('poly', 'x^2 - x - 6', '(x+2)(x-3)')
    expect(ok(s, 'x^2-x-6')).toBe(true)
    expect(ok(s, '-6 - x + x²')).toBe(true)
    expect(ok(s, '(x+2)(x-3)')).toBe(false)
    expect(ok(s, 'x^2 + x - 2x - 6')).toBe(false)
    expect(ok(s, 'x^2 - x + 6')).toBe(false)
    expect(checkAlgebra(s, 'x^2 + 5').note).toMatch(/not equal/)
    expect(checkAlgebra(s, 'x^2-x-6+').invalid).toBe(true)
    expect(ok(s, 'f(x) = x^2 - x - 6')).toBe(true)
  })
  it('factored form: must be fully factored, any order or arrangement', () => {
    const s = spec('factor', '3x(2x - 3)', '6x^2 - 9x')
    expect(ok(s, '3x(2x-3)')).toBe(true)
    expect(ok(s, '(2x-3)(3x)')).toBe(true)
    expect(ok(s, 'x(6x-9)')).toBe(false)
    expect(checkAlgebra(s, 'x(6x-9)').note).toMatch(/common number inside/)
    expect(ok(s, '3(2x^2-3x)')).toBe(false)
    expect(checkAlgebra(s, '3x(2x+3)').note).toMatch(/does not give/)
    expect(checkAlgebra(s, '6x^2-9x').note).toMatch(/not factored/)
    const q = spec('factor', '-(x - 1)(x + 2)', '-x^2 - x + 2')
    expect(ok(q, '(1-x)(x+2)')).toBe(true)
    expect(ok(q, '(x-1)(-x-2)')).toBe(true)
    expect(ok(q, '(x-1)(x+2)')).toBe(false)
    const c = spec('factor', '(x - 2)(x + 2)(x^2 + 4)', 'x^4 - 16')
    expect(ok(c, '(x^2-4)(x^2+4)')).toBe(false)
    expect(ok(c, '(x+2)(x^2+4)(x-2)')).toBe(true)
    const m = spec('factor', '2y(x - 3y)(x^2 + 3xy + 9y^2)', '2x^3y - 54y^4')
    expect(ok(m, '2y(x-3y)(x^2+3xy+9y^2)')).toBe(true)
    expect(ok(m, '(2y)(x-3y)(9y^2+3xy+x^2)')).toBe(true)
    expect(ok(spec('factor', '(x + 3)^2', 'x^2 + 6x + 9'), '(x+3)(x+3)')).toBe(true)
  })
  it('rational form: equal and in lowest terms', () => {
    const s = spec('rational', '(x + 2)/(x + 3)', '(x^2 - x - 6)/(x^2 - 9)')
    expect(ok(s, '(x+2)/(x+3)')).toBe(true)
    expect(ok(s, '(2x+4)/(2x+6)')).toBe(true)
    expect(ok(s, '(x^2+2x)/(x^2+3x)')).toBe(false)
    expect(checkAlgebra(s, '(x^2-x-6)/(x^2-9)').note).toMatch(/simplest form/)
    expect(ok(s, '1 - 1/(x+3)')).toBe(true)
    expect(ok(s, '(x+1)/(x+3)')).toBe(false)
    const t = spec('rational', '(x + y)/(y - x)', '(1/x + 1/y)/(1/x - 1/y)')
    expect(ok(t, '(x+y)/(y-x)')).toBe(true)
    expect(ok(t, '-(x+y)/(x-y)')).toBe(true)
    expect(ok(t, '(1/x+1/y)/(1/x-1/y)')).toBe(false)
    const p = spec('rational', 'x + 3', '(x^2 - 9)/(x - 3)')
    expect(ok(p, 'x+3')).toBe(true)
    expect(ok(p, '(x^2-9)/(x-3)')).toBe(false)
  })
  it('solve-for answers: any equivalent form, without the letter itself', () => {
    const s = spec('equiv', 'f*u/(u - f)', '1/f = 1/u + 1/v', 'v')
    expect(ok(s, 'v = fu/(u-f)')).toBe(true)
    expect(ok(s, '1/(1/f-1/u)')).toBe(true)
    expect(ok(s, 'u f/(u - f)')).toBe(true)
    expect(ok(s, 'fu/(f-u)')).toBe(false)
    expect(checkAlgebra(s, 'f u / v').note).toMatch(/still contains v/)
  })
})

describe('worked examples in the lessons are correct', () => {
  const same = (a: string, b: string) => expect(rEq(parseRat(a), parseRat(b)), `${a}  ==  ${b}`).toBe(true)
  it('expanding', () => {
    same('3x(2x - 5y + 4)', '6x^2 - 15xy + 12x')
    same('(2x - 3)(x + 5)', '2x^2 + 7x - 15')
    same('(2x - 3y)^2', '4x^2 - 12xy + 9y^2')
    same('(x + 2)^3', 'x^3 + 6x^2 + 12x + 8')
    same('(x + 3)^2 - (x - 1)(x + 5)', '2x + 14')
    same('(a + b + c)^2', 'a^2 + b^2 + c^2 + 2ab + 2ac + 2bc')
  })
  it('factoring', () => {
    same('6x^2y - 9xy^2', '3xy(2x - 3y)')
    same('x^2 - 5x - 24', '(x - 8)(x + 3)')
    same('6x^2 + 7x - 3', '(3x - 1)(2x + 3)')
    same('27x^3 - 8y^3', '(3x - 2y)(9x^2 + 6xy + 4y^2)')
    same('x^4 - 16', '(x - 2)(x + 2)(x^2 + 4)')
    same('x^3 - 3x^2 - 4x + 12', '(x - 3)(x - 2)(x + 2)')
    same('x^4 - 5x^2 + 4', '(x - 1)(x + 1)(x - 2)(x + 2)')
    same('x^2 + 5xy + 6y^2', '(x + 2y)(x + 3y)')
    same('(x + y)^2 - 9', '(x + y - 3)(x + y + 3)')
  })
  it('polynomials', () => {
    expect(rationalRoots(parsePoly('x^3 - 9x')).roots.map(fmtFrac)).toEqual(['−3', '0', '3'])
    expect(rationalRoots(parsePoly('2x^3 - x^2 - 13x - 6')).roots.map(fmtFrac)).toEqual(['−2', '−1/2', '3'])
    expect(rationalRoots(parsePoly('x^4 - 13x^2 + 36')).roots.map(fmtFrac)).toEqual(['−3', '−2', '2', '3'])
    expect(fmtPoly(pDivExact(parsePoly('x^3 + 2x^2 - 5x - 6'), parsePoly('x - 2'))!, true)).toBe('x^2 + 4x + 3')
    expect(fmtPoly(pDivExact(parsePoly('2x^3 - x^2 - 13x - 6'), parsePoly('x + 2'))!, true)).toBe('2x^2 - 5x - 3')
    same('x^3 - 27', '(x - 3)(x^2 + 3x + 9)')
  })
  it('simplifying and combining rational expressions', () => {
    same('(x^2 - x - 6)/(x^2 - 9)', '(x + 2)/(x + 3)')
    same('(x^2 - 9)/(3 - x)', '-(x + 3)')
    same('(x^3 - y^3)/(x^2 - y^2)', '(x^2 + x*y + y^2)/(x + y)')
    same('(x^3 + 8)/(x^2 - 4)', '(x^2 - 2x + 4)/(x - 2)')
    same('12x^3y/(18xy^2)', '2x^2/(3y)')
    same('(x^2 - 1)/(x^2 + 3x) * (x + 3)/(x - 1)', '(x + 1)/x')
    same('(x^2 - 4)/(x + 3) / ((x - 2)/(x^2 - 9))', 'x^2 - x - 6')
    same('3/(x - 2) - 2/(x + 1)', '(x + 7)/((x - 2)(x + 1))')
    same('1/(x^2 - 4) + 1/(x^2 + 4x + 4)', '2x/((x - 2)(x + 2)^2)')
    same('a/b - b/a', '(a - b)(a + b)/(ab)')
    same('1/(x - 1) - 3/(x^3 - 1)', '(x + 2)/(x^2 + x + 1)')
    same('(1/x + 1/y)/(1/x - 1/y)', '(x + y)/(y - x)')
    same('(1/(x + h) - 1/x)/h', '-1/(x(x + h))')
  })
  it('solving rational equations and for a letter', () => {
    const a = solveEquation(parseRat('1/x + 1/(x - 1)'), parseRat('3/2'))
    expect(a.roots.map(fmtFrac)).toEqual(['1/3', '2'])
    expect(a.extraneous).toEqual([])
    const b = solveEquation(parseRat('x/(x - 2)'), parseRat('2/(x - 2)'))
    expect(b.roots).toEqual([])
    expect(b.extraneous.map(fmtFrac)).toEqual(['2'])
    const c = solveEquation(parseRat('1/(x - 2) + 1/(x + 2)'), parseRat('4/(x^2 - 4)'))
    expect(c.roots).toEqual([])
    expect(c.extraneous.map(fmtFrac)).toEqual(['2'])
    expect(solveEquation(parseRat('3/x'), parseRat('6/(x + 2)')).roots.map(fmtFrac)).toEqual(['2'])
    // 1/f = 1/u + 1/v  =>  v = fu/(u - f)
    same('1/(1/f - 1/u)', 'f*u/(u - f)')
    // y = (x + 2)/(x - 3)  =>  x = (3y + 2)/(y - 1): substituting must give back y
    same('((3y + 2)/(y - 1) + 2)/((3y + 2)/(y - 1) - 3)', 'y')
  })
})
